import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_storage/firebase_storage.dart';
import 'package:hive_flutter/hive_flutter.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

import 'app/app.dart';
import 'services/staff_access_api.dart';
import 'firebase_options.dart'; // auto-generated by flutterfire configure

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize sqflite for desktop platforms (required for cached_network_image)
  if (Platform.isWindows || Platform.isLinux || Platform.isMacOS) {
    sqfliteFfiInit();
    databaseFactory = databaseFactoryFfi;
  }

  // Load environment variables (optional if you actually use them elsewhere)
  await dotenv.load(fileName: '.env');

  if (firebaseEmulatorHost.isNotEmpty && !kDebugMode) {
    throw StateError(
        'The demo Firebase project is only available in debug builds.');
  }

  // Initialize Firebase with the generated options
  await Firebase.initializeApp(
    options: firebaseEmulatorHost.isEmpty
        ? DefaultFirebaseOptions.currentPlatform
        : const FirebaseOptions(
            apiKey: 'demo-api-key',
            appId: '1:1234567890:ios:1234567890abcdef',
            messagingSenderId: '1234567890',
            projectId: firebaseDemoProject,
            storageBucket: '$firebaseDemoProject.appspot.com',
          ),
  );

  if (firebaseEmulatorHost.isNotEmpty) {
    await FirebaseAuth.instance.useAuthEmulator(firebaseEmulatorHost, 9099);
    FirebaseFirestore.instance.useFirestoreEmulator(firebaseEmulatorHost, 8080);
    await FirebaseStorage.instance
        .useStorageEmulator(firebaseEmulatorHost, 9199);
  }

  // Initialize Hive early to prevent initialization errors
  try {
    await Hive.initFlutter(
        firebaseEmulatorHost.isEmpty ? null : 'demo-firebase');
  } catch (e) {
    // If Hive initialization fails, continue anyway - the app will handle it
    debugPrint('Hive initialization failed: $e');
  }

  runApp(
    const ProviderScope(
      child: BTSDeliveryApp(),
    ),
  );
}
